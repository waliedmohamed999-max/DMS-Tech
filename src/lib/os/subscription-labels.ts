/** Error text for an action result. */
export function subError(t: Labels, r: { error: string; field?: Record<string, string> }) {
  if (r.error === "VALIDATION" && r.field) {
    const [k, v] = Object.entries(r.field)[0] ?? [];
    if (v && t.errors[v]) return t.errors[v];
    if (k && t.errors[k]) return t.errors[k];
  }
  return t.errors[r.error] ?? t.fallback;
}
